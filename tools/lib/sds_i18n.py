"""Gabarit SDS bilingue — GL-12 (vague 2 / file C).

Constat (backlog, mesuré le 15/09 sur #176/#177) : les phrases fixes du
gabarit SDS n'existaient qu'en anglais, dans des documents dont tout le
contenu généré est en français (~4 % des segments, tous issus du gabarit).

Le gabarit (docs/sds/templates) écrit chaque texte fixe en anglais, dans
``{{ _("…") }}`` ; ce module rend la traduction selon la langue du projet.

- ``_`` (texte fixe) : **strict**. En français, une phrase absente du
  catalogue lève ``TraductionManquante`` — un SDS à moitié traduit ne part pas
  en silence. Le test ``test_vague2_c_gl12_gabarit_sds`` vérifie que chaque
  ``_("…")`` des gabarits a son entrée.
- ``_v`` (valeur de donnée : verdict, catégorie, sévérité) : traduite si elle
  est connue, rendue telle quelle sinon — c'est une donnée, on la montre.
- Langues : ``fr`` et ``en``. Une autre langue de projet est rendue en anglais
  et le dit au journal (WARNING) : pas de catalogue pour elle.
"""
from __future__ import annotations

