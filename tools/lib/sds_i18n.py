LANGUES = ("fr", "en")

MOIS_FR = ("janvier", "février", "mars", "avril", "mai", "juin", "juillet",
           "août", "septembre", "octobre", "novembre", "décembre")


class TraductionManquante(KeyError):
    """Texte fixe du gabarit sans traduction dans la langue demandée."""


def langue_du_projet(langue: Optional[str]) -> str:
    code = (langue or "en").strip().lower().split("-")[0].split("_")[0]
    if code not in LANGUES:
        logger.warning("[SDS i18n] langue de projet '%s' sans catalogue : rendu en anglais", langue)
        return "en"
    return code


