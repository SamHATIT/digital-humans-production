def traducteur(langue: str):
    """Rend ``(_, _v)`` pour la langue (``fr`` ou ``en``)."""
    catalogue = CATALOGUE_FR if langue == "fr" else None

    def _(texte: str) -> str:
        if catalogue is None:
            return texte
        if texte not in catalogue:
            raise TraductionManquante(f"gabarit SDS : pas de traduction '{langue}' pour {texte!r}")
        return catalogue[texte]

    def _v(valeur: Any) -> Any:
        if langue != "fr" or not isinstance(valeur, str):
            return valeur
        return VALEURS_FR.get(valeur, valeur)

    return _, _v


def mois_annee(date, langue: str) -> str:
    if not date:
        return ""
    if langue == "fr":
        return f"{MOIS_FR[date.month - 1]} {date.year}"
    return date.strftime("%B %Y")


def installer_i18n(env, langue: Optional[str]) -> str:
    """Pose ``_``, ``_v``, ``langue_sds`` et le filtre ``mois_annee`` sur un
    environnement Jinja ; rend la langue retenue."""
    code = langue_du_projet(langue)
    _, _v = traducteur(code)
    env.globals.update({"_": _, "_v": _v, "langue_sds": code})
    env.filters["mois_annee"] = lambda d: mois_annee(d, code)
    return code


_RE_TOC_UC = re.compile(r"^Use Cases — (\d+) UCs$")
_RE_TOC_COUV = re.compile(r"^Coverage Report — (.+)%$")


def localiser_contexte(contexte: Dict[str, Any], langue: str) -> Dict[str, Any]:
    """Traduit les chaînes fixes que tools/lib/collect_sds.py met dans le
    contexte (sommaire, statut, héros). Sans effet en anglais."""
    if langue != "fr":
        return contexte
    for entree in contexte.get("toc") or []:
        titre = entree.get("title", "")
        m_uc, m_couv = _RE_TOC_UC.match(titre), _RE_TOC_COUV.match(titre)
        if m_uc:
            entree["title"] = f"Cas d'usage — {m_uc.group(1)} cas d'usage"
        elif m_couv:
            entree["title"] = f"Rapport de couverture — {m_couv.group(1)} %"
        else:
            entree["title"] = TOC_FR.get(titre, titre)
        entree["author"] = TOC_FR.get(entree.get("author", ""), entree.get("author", ""))
    statut = contexte.get("status") or {}
    if statut.get("label"):
        statut["label"] = STATUTS_FR.get(statut["label"], statut["label"])
    heros = contexte.get("hero") or {}
    nom = ((contexte.get("project") or {}).get("name")) or ""
    if heros.get("title_html", "").endswith(",<br><em>structured</em><br>as a single brief."):
        heros["title_html"] = f"{nom},<br><em>structuré</em><br>en un seul brief."
    if heros.get("subtitle") == SOUS_TITRE_PAR_DEFAUT_EN:
        heros["subtitle"] = SOUS_TITRE_PAR_DEFAUT_FR
    return contexte
